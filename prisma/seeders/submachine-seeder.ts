export async function seedSubMachines() {
  // Siapkan list prefix dari data, urutkan dari panjang ke pendek biar match yang paling spesifik
  const prefixes = data.map((d) => d.code).sort((a, b) => b.length - a.length);

  // Buat machines
  const machineMap: Record<string, number> = {};
  for (const prefix of prefixes) {
    const machine = await prisma.machine.upsert({
      where: { code: prefix },
      update: {},
      create: { code: prefix },
    });
    machineMap[prefix] = machine.id;
  }

  // Buat sub_machines
  for (const code of codes) {
    // Cari prefix yang cocok
    const prefix = prefixes.find((p) => code.startsWith(p));
    if (!prefix) {
      console.warn(`⚠️ Prefix not found for code: ${code}`);
      continue;
    }

    await prisma.subMachine.upsert({
      where: { code },
      update: { machine_id: machineMap[prefix] },
      create: { code, machine_id: machineMap[prefix] },
    });
  }
}
